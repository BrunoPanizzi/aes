func runVectors(t *testing.T, decrypt bool) {
	for _, suite := range suiteVectors {
		for i, v := range suite.vectors {
			key, err := hex.DecodeString(v.key)
			if err != nil {
				t.Fatalf("%s vector %d: bad key hex: %v", suite.name, i, err)
			}
			pt, err := hex.DecodeString(v.plaintext)
			if err != nil {
				t.Fatalf("%s vector %d: bad plaintext hex: %v", suite.name, i, err)
			}
			ct, err := hex.DecodeString(v.ciphertext)
			if err != nil {
				t.Fatalf("%s vector %d: bad ciphertext hex: %v", suite.name, i, err)
			}

			var in, want []byte
			dir := "ciphertext"
			if decrypt {
				in, want, dir = ct, pt, "plaintext"
			} else {
				in, want = pt, ct
			}

			var got []byte
			var err2 error
			if decrypt {
				got, err2 = AesDecrypt(in, key)
			} else {
				got, err2 = AesEncrypt(in, key)
			}
			if err2 != nil {
				t.Fatalf("%s vector %d: unexpected error: %v", suite.name, i, err2)
			}
			if !slices.Equal(got, want) {
				t.Errorf("%s vector %d:\n got %s: %x\nwant %s: %x", suite.name, i, dir, got, dir, want)
			}
		}
	}
}

func TestEncryptKAT(t *testing.T) {
	runVectors(t, false)
}

func TestDecryptKAT(t *testing.T) {
	runVectors(t, true)
}

// TestRoundTrip: decrypt(encrypt(pt)) == pt for every vector,
// independent of the published expected outputs.
func TestRoundTrip(t *testing.T) {
	for _, suite := range suiteVectors {
		for i, v := range suite.vectors {
			key, _ := hex.DecodeString(v.key)
			pt, _ := hex.DecodeString(v.plaintext)
			ct, _ := hex.DecodeString(v.ciphertext)

			enc, err := AesEncrypt(pt, key)
			if err != nil {
				t.Fatalf("%s vector %d: encrypt error: %v", suite.name, i, err)
			}
			dec, err := AesDecrypt(enc, key)
			if err != nil {
				t.Fatalf("%s vector %d: decrypt error: %v", suite.name, i, err)
			}
			if !slices.Equal(dec, pt) {
				t.Errorf("%s vector %d: round trip broken:\nplaintext:  %x\nciphertext: %x\nrecovered:  %x", suite.name, i, pt, ct, dec)
			}
			if !slices.Equal(enc, ct) {
				t.Errorf("%s vector %d: encrypt mismatch:\n got: %x\nwant: %x", suite.name, i, enc, ct)
			}
		}
	}
}
